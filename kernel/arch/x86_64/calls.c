// x86_64 clone has the last two arguments the other way round from i386 and
// arm64: clone(flags, stack, parent_tid, child_tid, tls)
static dword_t sys_clone_x86_64(dword_t flags, addr_t stack, addr_t ptid, addr_t ctid, addr_t tls) {
    return sys_clone(flags, stack, ptid, tls, ctid);
}

// creat(path, mode) is open(path, O_CREAT|O_WRONLY|O_TRUNC, mode)
static fd_t sys_creat(addr_t path_addr, mode_t_ mode) {
    return sys_open(path_addr, 01101, mode);
}

