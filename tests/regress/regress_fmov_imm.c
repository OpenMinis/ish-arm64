static int fails;

static void check_d(int imm8, double got) {
    uint64_t g; memcpy(&g, &got, 8);
    if (g != expect_d[imm8]) {
        if (fails < 10)
            printf("  FAIL  fmov d0,#imm8=0x%02x  got 0x%016llx  want 0x%016llx  (%.17g vs %.17g)\n",
                   imm8, (unsigned long long)g, (unsigned long long)expect_d[imm8],
                   got, *(const double *)&expect_d[imm8]);
        fails++;
    }
}

static void check_s(int imm8, float got) {
    uint32_t g; memcpy(&g, &got, 4);
    if (g != expect_s[imm8]) {
        if (fails < 10)
            printf("  FAIL  fmov s0,#imm8=0x%02x  got 0x%08x  want 0x%08x\n",
                   imm8, g, expect_s[imm8]);
        fails++;
    }
}

int main(void) {
    static double d[256];
    static float  s[256];
    int before;

    printf("=== FMOV (scalar immediate) decode, all 256 imm8 values ===\n");

    fmov_imm_d_table(d);
    before = fails;
    for (int i = 0; i < 256; i++)
        check_d(i, d[i]);
    printf("  double form: %d/256 correct\n", 256 - (fails - before));

    fmov_imm_s_table(s);
    before = fails;
    for (int i = 0; i < 256; i++)
        check_s(i, s[i]);
    printf("  single form: %d/256 correct\n", 256 - (fails - before));

    // The exact constants V8's ieee754::cos loads for |x| just under pi/4.
    // 0.71875 + 0.28125 == 1.0; decoded 8x too large they sum to 16, which is
    // where the +15 in Math.cos(Math.PI/4) came from.
    printf("=== V8 ieee754::cos range-reduction constants ===\n");
    double c1 = d[0x67], c2 = d[0x52];
    printf("  #0.71875 -> %.17g\n", c1);
    printf("  #0.28125 -> %.17g\n", c2);
    printf("  sum      -> %.17g (want 1)\n", c1 + c2);
    if (c1 != 0.71875 || c2 != 0.28125 || c1 + c2 != 1.0) {
        printf("  FAIL  cos C1/C2 constants wrong\n");
        fails++;
    }

    printf("\n================ RESULT ================\n");
    printf("  FAILURES: %d\n", fails);
    return fails ? 1 : 0;
}
