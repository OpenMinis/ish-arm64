// Regression test for the scalar FMOV (immediate) decode bug.
//
// gen.c has two call sites that expand an 8-bit AArch64 FP immediate via
// arm64_fpimm_to_bits(). That helper expects imm8 with bit6 ALREADY inverted.
// gen_simd_fp() did that (`imm8_raw ^ 0x40`); the scalar FMOV path did not, and
// passed the raw imm8 straight through. Every scalar `FMOV Dd/Sd, #imm` was
// therefore mis-scaled by 8x -- #0.71875 decoded as 11.5, #1.0 as 16.
//
// V8's ieee754::cos loads its C1/C2 range-reduction constants with exactly
// this instruction (fmov d0,#0.71875 / fmov d30,#0.28125, which sum to 1.0).
// Decoded as 11.5 + 4.5 = 16, cos(x) came back as the correct value + 15 for
// |x| just under pi/4 -- Math.cos(Math.PI/4) === 15.707106781186546.
//
// This sweeps ALL 256 imm8 encodings for both the double and single forms.
// The expected values are not re-derived from the spec here: they were dumped
// from real Apple Silicon hardware executing the same instructions, so this
// compares the emulator against the machine it emulates.
//
// Build: aarch64-linux-musl-gcc -static -O0 -o regress_fmov_imm
//            regress_fmov_imm.c regress_fmov_imm.S
// Run:   ish -r <rootfs> /tmp/regress_fmov_imm

